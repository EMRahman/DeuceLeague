-- Player logins: a login link, and the session it is exchanged for.
--
-- An access grant is now one of two kinds. A login link works once and
-- expires within minutes, so it must have an expiry. A session has none: a
-- player signs in once per phone, because a league is used a few times a month
-- and a login screen each time is how players drift away. It ends when it is
-- signed out, or when the member is removed.
--
-- Revoking a grant deletes it. A link is deleted when it is exchanged, which
-- is also what makes it work only once: two exchanges racing for the same link
-- both try to delete it, and only one finds it. So used_at goes; nothing is
-- kept that no longer works, and there is nothing personal left behind.
