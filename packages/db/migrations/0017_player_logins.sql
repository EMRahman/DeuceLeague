-- [hand] A live grant — a link that has not expired, or a session — for a
-- member who has not been removed. The API checks its kind: a link is good
-- only for being exchanged, and is deleted when it is.
CREATE FUNCTION deuceleague_resolve_access_grant(token_hash text)
  RETURNS TABLE (club_id uuid, access_grant_id uuid, member_id uuid, kind text, scopes text[])
  LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp
  AS $$
    SELECT g.club_id, g.id, g.member_id, g.kind, g.scopes
    FROM access_grant g
    JOIN member mb ON mb.id = g.member_id AND mb.deleted_at IS NULL
    WHERE g.token_hash = deuceleague_resolve_access_grant.token_hash
      AND (g.expires_at IS NULL OR g.expires_at > now())
  $$;
